function PositionLifecycleStoryHost({ data }: { data: PositionDetailResponse }) {
  const queryClient = useMemo(() => {
    const client = new QueryClient({
      defaultOptions: {
        queries: {
          retry: false,
          refetchInterval: false,
          staleTime: Infinity,
        },
      },
    })
    client.setQueryData(['insights', 'status'], {
      network: data.network,
      blockNumber: '333122000',
      observedAt: data.observedAt,
    })
    client.setQueryData(
      ['insights', 'wallets', data.account.toLowerCase(), 'positions', data.position.positionId],
      data,
    )
    return client
  }, [data])

  return (
    <QueryClientProvider client={queryClient}>
      <MemoryRouter initialEntries={[`/wallets/${data.account}/positions/${data.position.positionId}`]}>
        <div className="min-h-screen bg-[#14080e] p-6 text-[#f5efe6] sm:p-10">
          <div className="mx-auto max-w-6xl">
            <Routes>
              <Route path="/wallets/:address/positions/:positionId" element={<PositionLifecyclePage />} />
            </Routes>
          </div>
        </div>
      </MemoryRouter>
    </QueryClientProvider>
  )
}

