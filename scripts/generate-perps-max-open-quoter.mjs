#!/usr/bin/env node
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const project = resolve(root, 'apps/frontend/contracts/max-open')
const outputPath = resolve(root, 'apps/frontend/src/contracts/generated/perpsMaxOpenQuoter.ts')
const check = process.argv.includes('--check')
assert.ok(process.argv.slice(2).every(arg => arg === '--check'), 'Usage: node scripts/generate-perps-max-open-quoter.mjs [--check]')
const compilerVersion = '0.8.35+commit.47b9dedd'
const svmCompiler = resolve(homedir(), '.svm/0.8.35/solc-0.8.35')
const solc = process.env.SOLC_BINARY ?? (existsSync(svmCompiler) ? svmCompiler : 'solc')
assert.ok(execFileSync(solc, ['--version'], { encoding: 'utf8' }).includes(`Version: ${compilerVersion}`),
  `Use solc ${compilerVersion}; set SOLC_BINARY to its executable`)
const sourceNames = ['FullPrecisionMath.sol', 'PerpsMaxOpenQuoter.sol']
const sources = Object.fromEntries(sourceNames.map(name => [name, { content: readFileSync(resolve(project, name), 'utf8') }]))
const settings = {
  optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: 'cancun',
  metadata: { bytecodeHash: 'none', appendCBOR: false },
  outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
}
const compiled = JSON.parse(execFileSync(solc, ['--standard-json'], {
  input: JSON.stringify({ language: 'Solidity', sources, settings }), encoding: 'utf8', maxBuffer: 8 * 1024 * 1024,
}))
const errors = compiled.errors?.filter(error => error.severity === 'error') ?? []
assert.equal(errors.length, 0, errors.map(error => error.formattedMessage).join('\n'))

const stripInternalType = value => Array.isArray(value) ? value.map(stripInternalType)
  : value && typeof value === 'object'
    ? Object.fromEntries(Object.entries(value).filter(([key]) => key !== 'internalType').map(([key, child]) => [key, stripInternalType(child)]))
    : value
const canonicalSource = readFileSync(resolve(root, 'apps/frontend/src/contracts/abis/Perps.ts'), 'utf8')
const canonicalStart = canonicalSource.indexOf('export const PERPS_CFD_ENGINE_LENS_ABI = ') + 'export const PERPS_CFD_ENGINE_LENS_ABI = '.length
assert.ok(canonicalStart >= 'export const PERPS_CFD_ENGINE_LENS_ABI = '.length)
const canonical = JSON.parse(canonicalSource.slice(canonicalStart, canonicalSource.indexOf('] as const', canonicalStart) + 1))
const localLensAbi = compiled.contracts['PerpsMaxOpenQuoter.sol'].IPerpsMaxOpenLens.abi
for (const name of ['quoteMaxOpen', 'previewOpen']) {
  const expected = canonical.find(item => item.type === 'function' && item.name === name)
  const actual = localLensAbi.find(item => item.type === 'function' && item.name === name)
  assert.ok(expected && actual, `Missing canonical lens function ${name}`)
  assert.deepEqual(stripInternalType(actual), stripInternalType(expected), `Local ${name} interface differs from canonical ABI`)
}
const contract = compiled.contracts['PerpsMaxOpenQuoter.sol'].PerpsMaxOpenQuoter
const bytecode = `0x${contract.evm.bytecode.object}`
assert.ok(bytecode.length > 2 && !bytecode.includes('_'), 'Missing or unlinked helper creation bytecode')
const sha256 = value => createHash('sha256').update(value).digest('hex')
const provenance = { compiler: compilerVersion, settings, sourceSha256: sha256(JSON.stringify(sources)), creationBytecodeSha256: sha256(bytecode) }
const output = `// Generated by scripts/generate-perps-max-open-quoter.mjs. Do not edit.\n` +
  `// Deployless creation bytecode; it is only executed inside eth_call.\n` +
  `export const PERPS_MAX_OPEN_QUOTER_PROVENANCE = ${JSON.stringify(provenance, null, 2)} as const\n\n` +
  `export const PERPS_MAX_OPEN_QUOTER_ABI = ${JSON.stringify(stripInternalType(contract.abi), null, 2)} as const\n\n` +
  `export const PERPS_MAX_OPEN_QUOTER_BYTECODE = '${bytecode}' as const\n`
if (check) {
  assert.equal(readFileSync(outputPath, 'utf8'), output, 'Generated Max quoter is stale; rerun this script without --check')
} else {
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, output)
}
console.log(`${check ? 'Verified' : 'Generated'} deployless Max quoter (${(bytecode.length - 2) / 2} creation bytes)`)
